import assert from 'node:assert/strict';
import { pollingInterval, installActivityRefresh } from './activity-polling.ts';

const originalNow = Date.now;
let now = originalNow();
Date.now = () => now;
const doc = new EventTarget() as EventTarget & { visibilityState: string };
doc.visibilityState = 'visible';
const win = new EventTarget();
Object.assign(globalThis, { document: doc, window: win });
let refreshes = 0;
const stop = installActivityRefresh(() => { refreshes++; });
assert.equal(pollingInterval(30_000), 30_000);
now += 61_000;
assert.equal(pollingInterval(30_000), false);
assert.equal(pollingInterval(4000, true), 4000);
doc.visibilityState = 'hidden';
assert.equal(pollingInterval(4000, true), false);
doc.visibilityState = 'visible';
doc.dispatchEvent(new Event('visibilitychange'));
assert.equal(refreshes, 1);
assert.equal(pollingInterval(30_000), 30_000);
win.dispatchEvent(new Event('pointerdown'));
assert.equal(refreshes, 1);
stop();
now += 61_000;
win.dispatchEvent(new Event('pointerdown'));
assert.equal(refreshes, 1);
Date.now = originalNow;
console.info(JSON.stringify({ status: 'PASS', assertions: 8, method: 'Unit test with controlled clock and visibility; not measured browser requests' }));
